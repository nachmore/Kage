//! The process side of `run_user_shell_command` (see the parent module):
//! argument validation, the shell a command runs in, the output tail, and
//! the spawn / stream / timeout / cancel loop. No Tauri types, so all of it
//! is unit-testable with harmless commands.

use serde::Serialize;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, ExitStatus, Stdio};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc;
use std::sync::Arc;
use std::time::{Duration, Instant};

/// Longest command accepted, in bytes (UTF-8). Mirrored in
/// `ui/js/shared/shell-run.js`.
pub const MAX_COMMAND_BYTES: usize = 32 * 1024;

/// Output kept per run: the last this-many bytes of stdout + stderr.
/// Mirrored in `ui/js/shared/shell-run.js`.
pub const OUTPUT_TAIL_BYTES: usize = 64 * 1024;

/// A run still going after this long is stopped (its process group killed).
pub const RUN_TIMEOUT: Duration = Duration::from_secs(10 * 60);

/// Output is handed to `on_output` at most this often.
pub const EMIT_INTERVAL: Duration = Duration::from_millis(100);

/// How often the loop looks at the child, the cancel flag and the clock
/// when no output arrives.
const POLL: Duration = Duration::from_millis(50);

/// After the shell exits, how long to keep reading output still in the
/// pipes. A background job the command started (`server &`) can hold them
/// open indefinitely; its output after this is not collected.
const DRAIN_GRACE: Duration = Duration::from_secs(2);

const READ_CHUNK: usize = 8 * 1024;

/// Chunks buffered between the pipe readers and the loop. Bounded so a
/// command printing faster than we process (`yes`) blocks on its writes
/// instead of growing our memory.
const CHANNEL_CHUNKS: usize = 64;

/// Run ids are generated by the window (`kage-run-<n>`); anything else is
/// refused rather than echoed into events and logs.
const MAX_RUN_ID_LEN: usize = 64;

/// Why a run was refused before anything was spawned.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum InvalidRun {
    EmptyCommand,
    CommandTooLong,
    /// A NUL byte can't be passed in an argument (and has no business in a
    /// command line).
    NulInCommand,
    BadRunId,
    /// Run in Terminal types the command into an interactive shell, which
    /// reads a tab as "complete this" and a carriage return or escape as
    /// a keystroke: what ran would differ from what the user approved.
    ControlCharForTerminal,
    NoHome,
    CwdNotAbsolute(String),
    CwdMissing(String),
    CwdNotDirectory(String),
}

/// The command must be non-blank, at most [`MAX_COMMAND_BYTES`] and free of
/// NUL bytes. It is never trimmed or otherwise changed: what the user
/// approved is exactly what runs.
pub fn validate_command(command: &str) -> Result<(), InvalidRun> {
    if command.trim().is_empty() {
        return Err(InvalidRun::EmptyCommand);
    }
    if command.len() > MAX_COMMAND_BYTES {
        return Err(InvalidRun::CommandTooLong);
    }
    if command.contains('\0') {
        return Err(InvalidRun::NulInCommand);
    }
    Ok(())
}

/// [`validate_command`], plus what Run in Terminal needs: Terminal.app
/// types the command into the user's interactive shell as keystrokes, so
/// the only control character it may hold is `\n` (Return, which runs the
/// line). A tab would trigger completion and insert text the user never
/// saw; a carriage return, escape or other control character would be
/// read as an editing key.
pub fn validate_terminal_command(command: &str) -> Result<(), InvalidRun> {
    validate_command(command)?;
    if command.chars().any(|c| c.is_control() && c != '\n') {
        return Err(InvalidRun::ControlCharForTerminal);
    }
    Ok(())
}

/// 1–64 characters of `[A-Za-z0-9_-]`.
pub fn validate_run_id(run_id: &str) -> Result<(), InvalidRun> {
    let ok = !run_id.is_empty()
        && run_id.len() <= MAX_RUN_ID_LEN
        && run_id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
    if ok {
        Ok(())
    } else {
        Err(InvalidRun::BadRunId)
    }
}

/// The directory a run starts in: `cwd` when given (a leading `~` or `~/`
/// means `home`), else `home`. It must be an absolute path to an existing
/// directory — checked here, before the confirm offers to run, and again
/// right before spawning.
pub fn resolve_cwd(cwd: Option<&str>, home: Option<&Path>) -> Result<PathBuf, InvalidRun> {
    let requested = cwd.map(str::trim).filter(|c| !c.is_empty());
    let path = match requested {
        None => home.ok_or(InvalidRun::NoHome)?.to_path_buf(),
        Some("~") => home.ok_or(InvalidRun::NoHome)?.to_path_buf(),
        Some(c) => match c.strip_prefix("~/") {
            Some(rest) => home.ok_or(InvalidRun::NoHome)?.join(rest),
            None => PathBuf::from(c),
        },
    };
    let shown = path.to_string_lossy().into_owned();
    if !path.is_absolute() {
        return Err(InvalidRun::CwdNotAbsolute(shown));
    }
    match std::fs::metadata(&path) {
        Ok(m) if m.is_dir() => Ok(path),
        Ok(_) => Err(InvalidRun::CwdNotDirectory(shown)),
        Err(_) => Err(InvalidRun::CwdMissing(shown)),
    }
}

// --- Which shell -------------------------------------------------------------

/// On Windows, which shell runs the command. PowerShell unless the caller
/// knows the agent's shell tool was `cmd` (kiro-cli's `execute_cmd`).
#[cfg_attr(not(windows), allow(dead_code))]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WindowsShell {
    PowerShell,
    Cmd,
}

#[cfg_attr(not(windows), allow(dead_code))]
impl WindowsShell {
    /// `"cmd"` → [`WindowsShell::Cmd`]; anything else (or nothing) →
    /// PowerShell.
    pub fn from_hint(hint: Option<&str>) -> Self {
        match hint {
            Some(h) if h.eq_ignore_ascii_case("cmd") => Self::Cmd,
            _ => Self::PowerShell,
        }
    }
}

/// Program and arguments that run one command string.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShellInvocation {
    pub program: PathBuf,
    pub args: Vec<String>,
    /// Appended verbatim after `args` (Windows `cmd`, whose quoting rules
    /// aren't the ones `Command` applies). Always `None` elsewhere.
    #[cfg_attr(not(windows), allow(dead_code))]
    pub raw_tail: Option<String>,
    /// Short name for the confirm and the log (`zsh`, `PowerShell`).
    pub label: String,
}

/// Shells that take a POSIX `sh` command line. A login shell outside this
/// family (fish, nushell, csh, …) would misread what the agent wrote, so
/// the fallback runs it instead.
#[cfg_attr(not(unix), allow(dead_code))]
const POSIX_FAMILY: &[&str] = &["sh", "bash", "zsh", "dash", "ksh", "mksh", "ash"];

/// Fallbacks when `$SHELL` isn't a usable POSIX-family shell.
#[cfg_attr(not(unix), allow(dead_code))]
const POSIX_FALLBACKS: &[&str] = &["/bin/zsh", "/bin/sh"];

#[cfg_attr(not(unix), allow(dead_code))]
fn is_posix_family(shell: &Path) -> bool {
    shell
        .file_name()
        .and_then(|n| n.to_str())
        .is_some_and(|n| POSIX_FAMILY.contains(&n))
}

/// The user's login shell for a run: `$SHELL` when it is an absolute path
/// to a usable POSIX-family shell, else `/bin/zsh`, else `/bin/sh`.
/// `usable` says whether a path is an executable file (injected for tests).
#[cfg_attr(not(unix), allow(dead_code))]
pub fn select_posix_shell(
    env_shell: Option<&std::ffi::OsStr>,
    usable: impl Fn(&Path) -> bool,
) -> PathBuf {
    if let Some(shell) = env_shell.filter(|s| !s.is_empty()).map(Path::new) {
        if shell.is_absolute() && is_posix_family(shell) && usable(shell) {
            return shell.to_path_buf();
        }
    }
    POSIX_FALLBACKS
        .iter()
        .map(Path::new)
        .find(|p| usable(p))
        .unwrap_or(Path::new("/bin/sh"))
        .to_path_buf()
}

/// An executable regular file.
#[cfg(unix)]
pub fn is_executable_file(path: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    std::fs::metadata(path)
        .map(|m| m.is_file() && m.permissions().mode() & 0o111 != 0)
        .unwrap_or(false)
}

/// `<shell> -l -c -- <command>`: a login shell, so `.zprofile` / `.profile`
/// set it up the way a terminal would (on top of `os::login_env`'s overlay).
/// The `--` matters: `sh`/`bash`/`zsh` take the command from the first
/// argument after `-c` that isn't an option, so a command starting with
/// `-` or `+` would otherwise be read as shell options and not run as
/// written.
#[cfg_attr(not(unix), allow(dead_code))]
pub fn posix_invocation(shell: &Path, command: &str) -> ShellInvocation {
    ShellInvocation {
        program: shell.to_path_buf(),
        args: vec!["-l".into(), "-c".into(), "--".into(), command.into()],
        raw_tail: None,
        label: shell
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_else(|| "sh".into()),
    }
}

/// Windows: `powershell.exe -NoLogo -NoProfile -NonInteractive -Command
/// <command>` (`Command` quotes the argument the way PowerShell's argv
/// parser reads it back), or `cmd.exe /D /S /C "<command>"` (passed raw:
/// with `/S`, cmd strips exactly the outer quotes and runs the rest as
/// typed; `/D` skips AutoRun, like `-NoProfile`).
#[cfg_attr(not(windows), allow(dead_code))]
pub fn windows_invocation(shell: WindowsShell, command: &str) -> ShellInvocation {
    match shell {
        WindowsShell::PowerShell => ShellInvocation {
            program: PathBuf::from("powershell.exe"),
            args: vec![
                "-NoLogo".into(),
                "-NoProfile".into(),
                "-NonInteractive".into(),
                "-Command".into(),
                command.into(),
            ],
            raw_tail: None,
            label: "PowerShell".into(),
        },
        WindowsShell::Cmd => ShellInvocation {
            program: PathBuf::from("cmd.exe"),
            args: vec!["/D".into()],
            raw_tail: Some(format!("/S /C \"{command}\"")),
            label: "cmd".into(),
        },
    }
}

/// How this platform runs `command` for the user.
pub fn user_shell_invocation(command: &str, windows_hint: Option<&str>) -> ShellInvocation {
    #[cfg(windows)]
    {
        windows_invocation(WindowsShell::from_hint(windows_hint), command)
    }
    #[cfg(unix)]
    {
        let _ = windows_hint;
        let shell = select_posix_shell(std::env::var_os("SHELL").as_deref(), is_executable_file);
        posix_invocation(&shell, command)
    }
}

// --- Output ------------------------------------------------------------------

/// Decodes a byte stream as UTF-8 across chunk boundaries: a character
/// split between two reads is held back until its last byte arrives;
/// invalid bytes become U+FFFD.
#[derive(Debug, Default)]
pub struct Utf8Stream {
    carry: Vec<u8>,
}

impl Utf8Stream {
    pub fn push(&mut self, bytes: &[u8]) -> String {
        let mut data = std::mem::take(&mut self.carry);
        data.extend_from_slice(bytes);
        let mut out = String::with_capacity(data.len());
        let mut rest: &[u8] = &data;
        loop {
            match std::str::from_utf8(rest) {
                Ok(s) => {
                    out.push_str(s);
                    break;
                }
                Err(e) => {
                    let (valid, after) = rest.split_at(e.valid_up_to());
                    out.push_str(&String::from_utf8_lossy(valid));
                    match e.error_len() {
                        Some(n) => {
                            out.push('\u{FFFD}');
                            rest = &after[n..];
                        }
                        None => {
                            // An incomplete character at the end: wait for
                            // the rest of it.
                            self.carry = after.to_vec();
                            break;
                        }
                    }
                }
            }
        }
        out
    }

    /// The stream ended: a character left incomplete becomes U+FFFD.
    pub fn finish(&mut self) -> String {
        if self.carry.is_empty() {
            String::new()
        } else {
            self.carry.clear();
            "\u{FFFD}".into()
        }
    }
}

/// The last `cap` bytes of a text stream (cut on a character boundary),
/// plus how many bytes went through it and how many were dropped.
#[derive(Debug)]
pub struct OutputTail {
    buf: String,
    cap: usize,
    total: u64,
    dropped: u64,
}

impl OutputTail {
    pub fn new(cap: usize) -> Self {
        Self {
            buf: String::new(),
            cap,
            total: 0,
            dropped: 0,
        }
    }

    pub fn push(&mut self, text: &str) {
        self.total += text.len() as u64;
        if text.len() >= self.cap {
            // Only the end of this chunk can survive.
            self.dropped += self.buf.len() as u64;
            self.buf.clear();
            let mut cut = text.len() - self.cap;
            while !text.is_char_boundary(cut) {
                cut += 1;
            }
            self.dropped += cut as u64;
            self.buf.push_str(&text[cut..]);
            return;
        }
        self.buf.push_str(text);
        if self.buf.len() > self.cap {
            let mut cut = self.buf.len() - self.cap;
            while !self.buf.is_char_boundary(cut) {
                cut += 1;
            }
            self.buf.drain(..cut);
            self.dropped += cut as u64;
        }
    }

    pub fn text(&self) -> &str {
        &self.buf
    }

    pub fn is_empty(&self) -> bool {
        self.buf.is_empty()
    }

    pub fn total_bytes(&self) -> u64 {
        self.total
    }

    pub fn dropped_bytes(&self) -> u64 {
        self.dropped
    }

    /// Hand over the kept text and forget it (the counters restart too).
    pub fn take(&mut self) -> (String, u64) {
        let dropped = self.dropped;
        self.total = 0;
        self.dropped = 0;
        (std::mem::take(&mut self.buf), dropped)
    }
}

// --- Running -----------------------------------------------------------------

/// How a run ended.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum RunOutcome {
    /// The shell exited on its own (any exit code).
    Exited,
    /// The user pressed Stop.
    Cancelled,
    /// Still running at the timeout.
    TimedOut,
}

impl RunOutcome {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Exited => "exited",
            Self::Cancelled => "cancelled",
            Self::TimedOut => "timed_out",
        }
    }
}

/// What a finished run reports back.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RunReport {
    pub outcome: RunOutcome,
    /// The shell's exit code; `None` when a signal ended it.
    pub exit_code: Option<i32>,
    /// The signal that ended it (Unix).
    pub signal: Option<i32>,
    pub duration_ms: u64,
    /// The last [`OUTPUT_TAIL_BYTES`] of stdout and stderr, interleaved in
    /// arrival order, as the command printed it (escape sequences included).
    pub output: String,
    /// Output before `output` was dropped.
    pub truncated: bool,
    /// Everything the command printed, in bytes.
    pub output_bytes: u64,
}

/// Stop request and time limit for one run.
#[derive(Debug, Clone)]
pub struct RunControl {
    pub cancel: Arc<AtomicBool>,
    pub timeout: Duration,
}

/// Kill the whole tree the run started: the shell leads its own process
/// group and session (`configure_process_spawn`), so a group kill
/// (SIGTERM, then SIGKILL) reaches what it spawned; on Windows `taskkill
/// /T`. Only called while the child is unreaped, so its pid can't have been
/// reused.
fn kill_tree(child: &mut Child) {
    if !crate::os::process::kill_process(child.id()) {
        let _ = child.kill();
    }
}

fn spawn_reader<T: Read + Send + 'static>(
    mut pipe: T,
    stream: usize,
    tx: mpsc::SyncSender<(usize, Vec<u8>)>,
) {
    std::thread::spawn(move || {
        let mut buf = vec![0u8; READ_CHUNK];
        loop {
            match pipe.read(&mut buf) {
                Ok(0) => break,
                Ok(n) => {
                    if tx.send((stream, buf[..n].to_vec())).is_err() {
                        break;
                    }
                }
                Err(e) if e.kind() == std::io::ErrorKind::Interrupted => continue,
                Err(_) => break,
            }
        }
    });
}

fn exit_parts(status: &ExitStatus) -> (Option<i32>, Option<i32>) {
    #[cfg(unix)]
    {
        use std::os::unix::process::ExitStatusExt;
        (status.code(), status.signal())
    }
    #[cfg(not(unix))]
    {
        (status.code(), None)
    }
}

/// Output on its way from the pipes to `on_output`.
struct OutputSink<F: FnMut(&str, u64)> {
    decoders: [Utf8Stream; 2],
    kept: OutputTail,
    pending: OutputTail,
    last_emit: Instant,
    on_output: F,
}

impl<F: FnMut(&str, u64)> OutputSink<F> {
    fn push(&mut self, stream: usize, bytes: &[u8]) {
        let text = self.decoders[stream].push(bytes);
        self.add(&text);
    }

    fn add(&mut self, text: &str) {
        if text.is_empty() {
            return;
        }
        self.kept.push(text);
        self.pending.push(text);
    }

    fn emit(&mut self, force: bool) {
        if self.pending.is_empty() || (!force && self.last_emit.elapsed() < EMIT_INTERVAL) {
            return;
        }
        let (text, skipped) = self.pending.take();
        (self.on_output)(&text, skipped);
        self.last_emit = Instant::now();
    }

    fn finish(&mut self) {
        let rest: String = self.decoders.iter_mut().map(Utf8Stream::finish).collect();
        self.add(&rest);
        self.emit(true);
    }
}

/// Run `inv` in `cwd` with stdin closed, streaming stdout + stderr to
/// `on_output(text, skipped_bytes)` at most every [`EMIT_INTERVAL`]
/// (`skipped_bytes`: output printed since the last call that didn't fit
/// in one [`OUTPUT_TAIL_BYTES`] batch), until it exits, `control.cancel`
/// is set, or `control.timeout` passes — the last two kill its process
/// group. Blocks: call from a blocking thread. The login-shell environment
/// overlay (`os::login_env::apply`) is applied here, which can itself wait
/// for the first probe.
pub fn run(
    inv: &ShellInvocation,
    cwd: &Path,
    control: &RunControl,
    on_output: impl FnMut(&str, u64),
) -> std::io::Result<RunReport> {
    let mut cmd = Command::new(&inv.program);
    cmd.args(&inv.args);
    #[cfg(windows)]
    if let Some(raw) = &inv.raw_tail {
        use std::os::windows::process::CommandExt;
        cmd.raw_arg(raw);
    }
    cmd.current_dir(cwd)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    crate::os::login_env::apply(&mut cmd);
    // Unix: own session and process group (no controlling terminal, so
    // `sudo` fails fast instead of prompting somewhere unseen, and Stop
    // can kill the whole group). Windows: no console window.
    crate::os::process::configure_process_spawn(&mut cmd);

    let started = Instant::now();
    let mut child = cmd.spawn()?;
    let (tx, rx) = mpsc::sync_channel::<(usize, Vec<u8>)>(CHANNEL_CHUNKS);
    if let Some(out) = child.stdout.take() {
        spawn_reader(out, 0, tx.clone());
    }
    if let Some(err) = child.stderr.take() {
        spawn_reader(err, 1, tx.clone());
    }
    drop(tx);

    let mut sink = OutputSink {
        decoders: [Utf8Stream::default(), Utf8Stream::default()],
        kept: OutputTail::new(OUTPUT_TAIL_BYTES),
        pending: OutputTail::new(OUTPUT_TAIL_BYTES),
        last_emit: Instant::now(),
        on_output,
    };

    let mut readers_done = false;
    let (outcome, status) = loop {
        if readers_done {
            std::thread::sleep(POLL);
        } else {
            match rx.recv_timeout(POLL) {
                Ok((stream, bytes)) => {
                    sink.push(stream, &bytes);
                    while let Ok((stream, bytes)) = rx.try_recv() {
                        sink.push(stream, &bytes);
                    }
                }
                Err(mpsc::RecvTimeoutError::Timeout) => {}
                Err(mpsc::RecvTimeoutError::Disconnected) => readers_done = true,
            }
        }
        sink.emit(false);
        match child.try_wait() {
            Ok(Some(status)) => break (RunOutcome::Exited, status),
            Ok(None) => {}
            Err(e) => {
                kill_tree(&mut child);
                let _ = child.wait();
                return Err(e);
            }
        }
        let stop = if control.cancel.load(Ordering::SeqCst) {
            Some(RunOutcome::Cancelled)
        } else if started.elapsed() >= control.timeout {
            Some(RunOutcome::TimedOut)
        } else {
            None
        };
        if let Some(outcome) = stop {
            kill_tree(&mut child);
            break (outcome, child.wait()?);
        }
    };

    // What's still in the pipes (or in flight from a killed group).
    let deadline = Instant::now() + DRAIN_GRACE;
    while !readers_done {
        let left = deadline.saturating_duration_since(Instant::now());
        if left.is_zero() {
            break;
        }
        match rx.recv_timeout(left) {
            Ok((stream, bytes)) => sink.push(stream, &bytes),
            Err(_) => readers_done = true,
        }
    }
    sink.finish();

    let (exit_code, signal) = exit_parts(&status);
    Ok(RunReport {
        outcome,
        exit_code,
        signal,
        duration_ms: u64::try_from(started.elapsed().as_millis()).unwrap_or(u64::MAX),
        output: sink.kept.text().to_owned(),
        truncated: sink.kept.dropped_bytes() > 0,
        output_bytes: sink.kept.total_bytes(),
    })
}

/// Telemetry bucket for how a run ended — never the command, never the
/// exact code beyond the conventional ranges.
pub fn outcome_bucket(report: &RunReport) -> &'static str {
    match report.outcome {
        RunOutcome::Cancelled => "cancelled",
        RunOutcome::TimedOut => "timeout",
        RunOutcome::Exited => match (report.exit_code, report.signal) {
            (Some(0), _) => "0",
            (Some(1), _) => "1",
            (Some(126), _) => "126",
            (Some(127), _) => "127",
            (Some(c), _) if (2..126).contains(&c) => "2-125",
            (Some(_), _) => "other",
            (None, Some(_)) => "signal",
            (None, None) => "other",
        },
    }
}

/// The program a command starts with, for the log line: the first word
/// that isn't a `NAME=value` assignment, as a basename, clipped. Never the
/// rest of the command (arguments can hold tokens and paths).
pub fn program_label(command: &str) -> String {
    let word = command
        .split_whitespace()
        .find(|w| {
            let Some((name, _)) = w.split_once('=') else {
                return true;
            };
            name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        })
        .unwrap_or("");
    let base = word.rsplit(['/', '\\']).next().unwrap_or(word);
    let clean: String = base
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | '+'))
        .take(32)
        .collect();
    if clean.is_empty() {
        "?".into()
    } else {
        clean
    }
}
